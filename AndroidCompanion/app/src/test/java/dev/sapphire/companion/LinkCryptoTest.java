package dev.sapphire.companion;

import org.junit.Test;

import static org.junit.Assert.*;

import java.util.*;
import java.security.*;
import java.security.spec.*;
import java.math.BigInteger;

public class LinkCryptoTest {
    private static byte[] seq(int start, int count) {
        byte[] b = new byte[count];
        for (int i = 0; i < count; i++) b[i] = (byte) (start + i);
        return b;
    }

    @Test
    public void ecdhAndSasAgree() throws Exception {
        KeyPair a = LinkCrypto.keyPair(), b = LinkCrypto.keyPair();
        byte[] ab = LinkCrypto.shared(a.getPrivate(), LinkCrypto.publicPoint(b.getPublic())), ba = LinkCrypto.shared(b.getPrivate(), LinkCrypto.publicPoint(a.getPublic()));
        assertArrayEquals(ab, ba);
        assertEquals(LinkCrypto.sas(ab, seq(0, 32)), LinkCrypto.sas(ba, seq(0, 32)));
    }

    @Test
    public void matchesMacJavaFixture() throws Exception {
        AlgorithmParameters p = AlgorithmParameters.getInstance("EC");
        p.init(new ECGenParameterSpec("secp256r1"));
        ECParameterSpec spec = p.getParameterSpec(ECParameterSpec.class);
        PrivateKey mac = KeyFactory.getInstance("EC").generatePrivate(new ECPrivateKeySpec(BigInteger.ONE, spec));
        // Scalar 2 public point used by the independently verified Mac fixture.
        byte[] point = HexFormat.of().parseHex("047cf27b188d034f7e8a52380304b51ac3c08969e277f21b35a60b48fc4766997807775510db8ed040293d9ac69f7430dbba7dade63ce982299e04b79d227873d1");
        byte[] shared = LinkCrypto.shared(mac, point), salt = seq(0, 32);
        byte[] key = LinkCrypto.hkdf(shared, salt, "sapphire-continuity-link", 32);
        // This fixed vector was generated by the independently verified Mac/Java fixture.
        java.io.InputStream fixture = getClass().getResourceAsStream("/android-crypto.json");
        assertNotNull(fixture);
        java.io.ByteArrayOutputStream bytes = new java.io.ByteArrayOutputStream();
        try (fixture) {
            byte[] buffer = new byte[1024];
            int count;
            while ((count = fixture.read(buffer)) != -1) bytes.write(buffer, 0, count);
        }
        org.json.JSONObject json = new org.json.JSONObject(new String(bytes.toByteArray(), java.nio.charset.StandardCharsets.UTF_8));
        assertEquals(json.getString("linkKey"), Base64.getEncoder().encodeToString(key));
        assertEquals(json.getString("sas"), LinkCrypto.sas(shared, salt));
        LinkCrypto.Session sender = new LinkCrypto.Session(key, seq(0, 32), seq(32, 32), false);
        assertEquals(json.getString("frame"), Base64.getEncoder().encodeToString(sender.seal(LinkCrypto.utf8("{\"type\":\"status.request\"}"))));
    }

    @Test
    public void authenticatedFramesAndReplays() throws Exception {
        byte[] key = seq(0, 32), m = seq(32, 32), p = seq(64, 32);
        LinkCrypto.Session mac = new LinkCrypto.Session(key, m, p, false), phone = new LinkCrypto.Session(key, m, p, true);
        byte[] a = mac.seal(LinkCrypto.utf8("one")), b = mac.seal(LinkCrypto.utf8("two"));
        assertArrayEquals(LinkCrypto.utf8("two"), phone.open(b));
        assertArrayEquals(LinkCrypto.utf8("one"), phone.open(a));
        assertThrows(Exception.class, () -> phone.open(a));
        byte[] good = mac.seal(LinkCrypto.utf8("three")), bad = good.clone();
        bad[bad.length - 1] ^= 1;
        assertThrows(Exception.class, () -> phone.open(bad));
        assertArrayEquals(LinkCrypto.utf8("three"), phone.open(good));
        assertArrayEquals(LinkCrypto.utf8("reply"), mac.open(phone.seal(LinkCrypto.utf8("reply"))));
    }

    @Test
    public void boundedFragments() throws Exception {
        for (int limit : new int[]{20, 185, 512}) {
            GattFrames frames = new GattFrames();
            byte[] result = null;
            for (byte[] b : GattFrames.split(seq(0, 256), 65535, limit)) {
                byte[] v = frames.accept(b, 0);
                if (v != null) result = v;
            }
            assertArrayEquals(seq(0, 256), result);
        }
        assertThrows(Exception.class, () -> new GattFrames().accept(new byte[]{2, 1, 0}, 0));
        assertThrows(Exception.class, () -> GattFrames.split(new byte[16385], 1, 20));
        GattFrames f = new GattFrames();
        List<byte[]> parts = GattFrames.split(new byte[100], 2, 20);
        f.accept(parts.get(0), 0);
        assertThrows(Exception.class, () -> f.accept(parts.get(1), 16000));
    }
}
