var delivery = MonitoringDeliveryPolicy()
assert(delivery.ticket(for: .cpu) == nil)
delivery.configure([.cpu, .lowDisk])
let cpu = delivery.ticket(for: .cpu)!
let disk = delivery.ticket(for: .lowDisk)!
assert(delivery.isCurrent(cpu) && delivery.isCurrent(disk))
delivery.configure([.cpu, .lowDisk]) // A threshold/configuration revision, even with the same active kinds.
assert(!delivery.isCurrent(cpu) && !delivery.isCurrent(disk))
let newer = delivery.ticket(for: .cpu)!
delivery.configure([])
delivery.configure([.cpu]) // Disable/re-enable cannot revive a pending authorization callback.
assert(!delivery.isCurrent(newer) && delivery.ticket(for: .temperature) == nil)
let final = delivery.ticket(for: .cpu)!
assert(delivery.isCurrent(final))
delivery.configure([]) // Teardown cancels delivery.
assert(!delivery.isCurrent(final))

